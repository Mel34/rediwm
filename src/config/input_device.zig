//! Persistent pointer overrides. Records match exact identities; omitted
//! properties inherit the legacy [input] defaults for the device's kind.
const std = @import("std");
const loader = @import("loader.zig");
const fields = @import("loader_fields.zig");

pub const Record = struct {
    id: []const u8 = "",
    pointer_speed: ?f32 = null,
    natural_scroll: ?bool = null,
    left_handed: ?bool = null,
    tap_to_click: ?bool = null,
    tap_drag: ?bool = null,
    disable_while_typing: ?bool = null,
};

pub const Effective = struct {
    pointer_speed: f32,
    natural_scroll: bool,
    left_handed: bool,
    tap_to_click: bool,
    tap_drag: bool,
    disable_while_typing: bool,
};

/// Keys are generated by the backend identity module, never display labels.
/// Do not accept escaping: the config's small string parser does not decode it.
pub fn validId(id: []const u8) bool {
    if (id.len == 0 or id.len > 1024) return false;
    for (id) |ch| if (ch < 0x21 or ch > 0x7e or ch == '"' or ch == '\\') return false;
    return true;
}

pub fn resolve(defaults: loader.InputConfig, records: []const Record, id: ?[]const u8, touchpad: bool) Effective {
    var effective: Effective = .{
        .pointer_speed = if (touchpad) defaults.pointer_speed_touchpad else defaults.pointer_speed,
        .natural_scroll = defaults.natural_scroll,
        .left_handed = defaults.left_handed,
        .tap_to_click = defaults.tap_to_click,
        .tap_drag = defaults.tap_drag,
        .disable_while_typing = if (touchpad) defaults.disable_while_typing_touchpad else defaults.disable_while_typing,
    };
    const identity = id orelse return effective;
    const record = find(records, identity) orelse return effective;
    inline for (@typeInfo(Effective).@"struct".field_names) |key| {
        if (@field(record, key)) |value| @field(effective, key) = value;
    }
    return effective;
}

/// Fail closed even for callers supplying unvalidated, hand-built records.
pub fn find(records: []const Record, id: []const u8) ?Record {
    if (!validId(id)) return null;
    var found: ?Record = null;
    for (records) |record| {
        if (!std.mem.eql(u8, record.id, id)) continue;
        if (found != null) return null;
        found = record;
    }
    return found;
}

/// Explicit values remain overrides even when equal to today's default.
pub fn isOverridden(records: []const Record, id: ?[]const u8, comptime key: []const u8) bool {
    _ = Value(key);
    const record = find(records, id orelse return false) orelse return false;
    return @field(record, key) != null;
}

pub fn hasOverrides(records: []const Record, id: ?[]const u8) bool {
    const record = find(records, id orelse return false) orelse return false;
    inline for (@typeInfo(Effective).@"struct".field_names) |key| {
        if (@field(record, key) != null) return true;
    }
    return false;
}

pub fn eql(a: []const Record, b: []const Record) bool {
    if (a.len != b.len) return false;
    for (a, b) |left, right| {
        if (!std.mem.eql(u8, left.id, right.id)) return false;
        inline for (@typeInfo(Effective).@"struct".field_names) |key| {
            if (@field(left, key) != @field(right, key)) return false;
        }
    }
    return true;
}

pub fn Value(comptime key: []const u8) type {
    return @FieldType(Effective, key);
}

pub fn validateValue(comptime key: []const u8, value: Value(key)) !void {
    if (comptime std.mem.eql(u8, key, "pointer_speed")) {
        if (!std.math.isFinite(value) or value < -1 or value > 1) return error.InvalidValue;
    }
}

pub const Prepared = struct {
    records: []Record,
    index: ?usize,
    record: Record,

    pub fn commit(self: Prepared, cfg: *loader.Config) void {
        if (self.index) |index| self.records[index] = self.record;
        cfg.input_devices = self.records;
    }
};

/// Allocate before touching the backend/file. Commit only after the setting
/// was accepted and saved. Existing records need no allocations, even when a
/// slider emits a stream of changes. New records belong to cfg's arena.
pub fn prepareSet(cfg: *loader.Config, id: []const u8, comptime key: []const u8, value: Value(key)) !Prepared {
    if (!validId(id)) return error.InvalidValue;
    try validateValue(key, value);
    var selected: ?usize = null;
    for (cfg.input_devices, 0..) |record, i| {
        if (!std.mem.eql(u8, record.id, id)) continue;
        if (selected != null) return error.InvalidConfig;
        selected = i;
    }
    var prepared: Prepared = undefined;
    if (selected) |index| {
        prepared = .{ .records = cfg.input_devices, .index = index, .record = cfg.input_devices[index] };
    } else {
        const a = cfg.arena.allocator();
        const records = try a.alloc(Record, cfg.input_devices.len + 1);
        @memcpy(records[0..cfg.input_devices.len], cfg.input_devices);
        prepared = .{ .records = records, .index = cfg.input_devices.len, .record = .{ .id = try a.dupe(u8, id) } };
    }
    @field(prepared.record, key) = value;
    return prepared;
}

/// Reset inherits future defaults as well as today's. Keep an existing id-only
/// record so file comments and record order can survive; never create a record
/// merely to reset a device that already inherits everything.
pub fn prepareReset(cfg: *loader.Config, id: []const u8) !Prepared {
    if (!validId(id)) return error.InvalidValue;
    var selected: ?usize = null;
    var empty: Record = .{};
    for (cfg.input_devices, 0..) |record, i| {
        if (!std.mem.eql(u8, record.id, id)) continue;
        if (selected != null) return error.InvalidConfig;
        selected = i;
        empty.id = record.id;
    }
    return .{ .records = cfg.input_devices, .index = selected, .record = empty };
}

/// Parser state deliberately notices empty records and duplicate fields, so
/// neither an incomplete matcher nor last-write-wins can target another device.
pub const Parser = struct {
    records: std.ArrayList(Record) = .empty,
    current: Record = .{},
    seen: std.enums.EnumSet(std.meta.FieldEnum(Record)) = .empty,

    pub fn apply(self: *Parser, a: std.mem.Allocator, key: []const u8, value: []const u8) !void {
        const field = std.meta.stringToEnum(std.meta.FieldEnum(Record), key) orelse return error.UnknownField;
        if (self.seen.contains(field)) return error.DuplicateField;
        const known = try fields.applyField(&self.current, a, fields.input_device_rules, key, value);
        if (!known) return error.UnknownField;
        self.seen.insert(field);
    }

    pub fn flush(self: *Parser, a: std.mem.Allocator) !void {
        if (!validId(self.current.id)) return error.InvalidIdentity;
        for (self.records.items) |record| if (std.mem.eql(u8, record.id, self.current.id)) return error.DuplicateIdentity;
        try self.records.append(a, self.current);
        self.current = .{};
        self.seen = .empty;
    }
};

